"""Designs the three decimating stages of AudioKodec's DSD to PCM conversion
and prints them as Kotlin, after checking each stage's response.

Every frequency is a fraction of the DSD rate fs. The output is at fs/32,
88.2 kHz for DSD64, in three stages:

  stage 1  fs     -> fs/8   79 taps, applied ten bytes at a time through tables
  stage 2  fs/8   -> fs/16
  stage 3  fs/16  -> fs/32

Each is a Kaiser-windowed sinc of odd length, so each delays by a whole number
of its input samples and the cascade can be centred exactly. The whole
conversion passes 0 to fs/128 (22.05 kHz for DSD64) flat, and attenuates by at
least ATTENUATION - 1 dB everything that would fold into 0 to fs/64, the output's
Nyquist frequency, at every stage.

Usage: python3 -I design-dsd-filters.py
"""
import math

ATTENUATION = 120.0
PASS = 1 / 128


def bessel_i0(x):
    total, term, k = 1.0, 1.0, 1
    while term > 1e-21 * total:
        term *= (x / (2 * k)) ** 2
        total += term
        k += 1
    return total


def kaiser_lowpass(length, cutoff, attenuation):
    """A lowpass of odd [length] taps, [cutoff] a fraction of its input rate, unit gain at zero."""
    assert length % 2 == 1
    beta = 0.1102 * (attenuation - 8.7)
    centre = (length - 1) / 2
    taps = []
    for n in range(length):
        t = n - centre
        ideal = 2 * cutoff if t == 0 else math.sin(2 * math.pi * cutoff * t) / (math.pi * t)
        window = bessel_i0(beta * math.sqrt(1 - (t / centre) ** 2)) / bessel_i0(beta)
        taps.append(ideal * window)
    gain = sum(taps)
    return [v / gain for v in taps]


def length_for(transition, attenuation):
    n = math.ceil((attenuation - 8) / (2.285 * 2 * math.pi * transition)) + 1
    return n if n % 2 == 1 else n + 1


def response_db(taps, f):
    re = sum(v * math.cos(2 * math.pi * f * n) for n, v in enumerate(taps))
    im = sum(v * math.sin(2 * math.pi * f * n) for n, v in enumerate(taps))
    return 20 * math.log10(max(math.hypot(re, im), 1e-300))


def check(name, taps, rate, pass_edge, stop_edge):
    """[rate] is the stage's input rate as a fraction of fs; the edges are fractions of fs."""
    ripple = max(abs(response_db(taps, f / rate)) for f in [pass_edge * i / 200 for i in range(201)])
    worst = max(response_db(taps, f / rate) for f in [stop_edge + (rate / 2 - stop_edge) * i / 2000 for i in range(2001)])
    assert ripple < 1e-4, (name, ripple)
    assert worst < -ATTENUATION + 1, (name, worst)
    return ripple, worst


stages = []
# Stage 1 at fs: must reject every band that folds into [0, fs/64] at fs/8.
s1_stop = 1 / 8 - 1 / 64
s1_len = length_for(s1_stop - PASS, ATTENUATION)
assert s1_len <= 79, s1_len
s1 = kaiser_lowpass(79, (PASS + s1_stop) / 2, ATTENUATION)
stages.append(("STAGE1", s1, 1.0, s1_stop))
# Stage 2 at fs/8, to fs/16: rejects what folds into [0, fs/64].
s2_stop = 1 / 16 - 1 / 64
s2_len = length_for((s2_stop - PASS) * 8, ATTENUATION + 3)
s2 = kaiser_lowpass(s2_len, (PASS + s2_stop) / 2 * 8, ATTENUATION + 3)
stages.append(("STAGE2", s2, 1 / 8, s2_stop))
# Stage 3 at fs/16, to fs/32: attenuates everything above the output's Nyquist frequency.
s3_stop = 1 / 64
s3_len = length_for((s3_stop - PASS) * 16, ATTENUATION + 3)
s3 = kaiser_lowpass(s3_len, (PASS + s3_stop) / 2 * 16, ATTENUATION + 3)
stages.append(("STAGE3", s3, 1 / 16, s3_stop))

print("        // Generated by design-dsd-filters.py: Kaiser-windowed sinc, %g dB." % ATTENUATION)
for name, taps, rate, stop in stages:
    ripple, worst = check(name, taps, rate, PASS, stop)
    print("        // %s: %d taps at %s, ripple %.2e dB to fs/128, at most %.1f dB from %s." % (
        name, len(taps), "fs" if rate == 1 else "fs/%d" % round(1 / rate), ripple, worst, "fs/%d" % round(1 / stop) if 1 / stop == round(1 / stop) else "%.6f fs" % stop))
    print("        private val %s: DoubleArray = doubleArrayOf(" % name)
    for i in range(0, len(taps), 4):
        print("            " + ", ".join(repr(v) for v in taps[i:i + 4]) + ",")
    print("        )")
