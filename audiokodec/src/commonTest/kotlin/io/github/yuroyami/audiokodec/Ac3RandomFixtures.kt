package io.github.yuroyami.audiokodec

import io.github.yuroyami.audiokodec.internal.tag.Base64

/**
 * Two syncframes each of AC-3 streams no encoder writes, and what ffmpeg's
 * decoder gives for them.
 *
 * ffmpeg's encoder never switches blocks and never writes delta bit
 * allocation, dynamic range words, phase flags or dual mono, so these come
 * from the JVM tests' `Ac3FrameWriter`, which picks every element of a frame
 * at random and packs it as ATSC A/52:2012 section 5 says. The JVM oracle suite
 * checks that the bytes below are what the writer gives for the seeds and shape
 * recorded with them, and decodes them again with ffmpeg.
 *
 * Recipe: write each syncframe with `Ac3FrameWriter(seed).frame(sampleRateCode,
 * codingMode, hasLfe, minimumSizeCode = 20)`, join the two, decode with `ffmpeg
 * -f ac3 -i x.ac3 -f f32le`. The digest holds every eighth frame of that decode,
 * channel by channel, in steps of 2^-24, and the RMS values the root mean
 * square of each channel of each syncframe. The noise is quiet, so that float
 * rounding is small beside it, and the dither flags are clear.
 */
internal object Ac3RandomFixtures {

    class Fixture(
        val name: String,
        /** The seeds `Ac3FrameWriter` was given for the two syncframes. */
        val seeds: List<Long>,
        val sampleRateCode: Int,
        val codingMode: Int,
        val hasLfe: Boolean,
        val bytes: ByteArray,
        val digest: IntArray,
        val rms: FloatArray,
        val rate: Int,
        val channels: Int,
        /** What the frames use that the encoders' streams do not: `sw` block switching, `cpl` coupling, `remat` rematrixing, `phase` phase flags, `delta` delta bit allocation, `dynrng` dynamic range words, `master` master coupling coordinates. */
        val uses: Set<String>,
    )

    private fun decode(base64: String): ByteArray = Base64.decodeOrNull(base64) ?: error("a fixture is not base64")

    private fun ints(base64: String): IntArray {
        val raw = decode(base64)
        return IntArray(raw.size / 4) {
            (raw[4 * it].toInt() and 0xFF) or ((raw[4 * it + 1].toInt() and 0xFF) shl 8) or
                ((raw[4 * it + 2].toInt() and 0xFF) shl 16) or (raw[4 * it + 3].toInt() shl 24)
        }
    }

