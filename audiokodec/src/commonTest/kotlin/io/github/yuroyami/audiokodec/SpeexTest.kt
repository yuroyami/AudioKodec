package io.github.yuroyami.audiokodec

import io.github.yuroyami.audiokodec.internal.tag.Base64
import kotlin.math.abs
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertTrue

/**
 * Checks Speex decoding on every target, against small files speexenc 1.2.1
 * wrote in each of the three modes, and samples of what libspeex 1.2.1
 * decodes them to, trimmed as speexdec trims them.
 *
 * The bound is 1e-3 of full scale. On the JVM the decoder gives the
 * reference's floats exactly, which the JVM oracle suite requires. Kotlin/JS
 * keeps Float arithmetic in double precision, and Speex runs its samples
 * through recursive filters, so there the last bits of the reference's
 * single-precision rounding are not reproduced and the difference builds up
 * along each filter, to 2.2e-4 in these files' ultra-wideband stream; the
 * bound leaves room above that, and is still a fraction of a step of the
 * 8-bit output a gross error would show as.
 */
class SpeexTest {

    @Test
    fun everyModeDecodesToTheReferenceSamples() {
        val cases = listOf(
            Triple(NARROWBAND, NARROWBAND_PICKS, Shape(8040, 1, 8_000)),
            Triple(WIDEBAND_STEREO, WIDEBAND_STEREO_PICKS, Shape(9680, 2, 16_000)),
            Triple(ULTRA_WIDEBAND, ULTRA_WIDEBAND_PICKS, Shape(12960, 1, 32_000)),
        )
        for ((file, picks, shape) in cases) {
            val what = "${shape.channels} ch at ${shape.rate} Hz"
            val bytes = decode(file)
            val info = AudioKodec.probe(bytes)
            assertEquals(AudioCodec.SPEEX, info.codec, what)
            assertEquals(shape.channels, info.format.channels, what)
            assertEquals(shape.rate, info.format.sampleRate, what)
            assertEquals(shape.frames.toLong(), info.durationFrames, what)
            val samples = AudioKodec.decode(bytes).samples
            assertEquals(shape.frames * shape.channels, samples.size, what)
            for (p in picks.indices step 2) {
                val expected = Float.fromBits(picks[p + 1])
                val actual = samples[picks[p]]
                assertTrue(abs(expected - actual) <= BOUND, "$what, sample ${picks[p]}: $actual, not $expected")
            }
        }
    }

    @Test
    fun aSeekToTheStartIsExactAndLaterSeeksConverge() {
        val bytes = decode(ULTRA_WIDEBAND)
        val whole = AudioKodec.decode(bytes).samples
        for (target in listOf(0L, 5000L, 12000L)) {
            AudioKodec.open(bytes).use { decoder ->
                assertEquals(target, decoder.seek(target))
                val block = decoder.nextFrame()!!
                for (i in 0 until minOf(block.frameCount, 200)) {
                    val diff = abs(whole[target.toInt() + i] - block.samples[i])
                    if (target == 0L) assertEquals(0f, diff, "seek to the start, sample $i")
                    assertTrue(diff < 1e-3f, "seek to $target, sample $i: $diff")
                }
            }
        }
    }

    @Test
    fun anUnknownModeAndALaterBitstreamAreRefused() {
        val bytes = decode(TINY)
        // The header packet starts the second page's payload after 28 + 1 bytes of page header.
        val header = 28 + 1
        val unknownMode = bytes.copyOf().also { it[header + 40] = 3 }
        assertFailsWith<AudioKodecException> { AudioKodec.decode(fixCrc(unknownMode)) }
        val laterBitstream = bytes.copyOf().also { it[header + 44] = 5 }
        assertFailsWith<UnsupportedFeatureException> { AudioKodec.open(fixCrc(laterBitstream)) }
    }

    @Test
    fun truncatedAndMutatedFilesFailOnlyWithTheLibrarysOwnExceptions() {
        for (file in listOf(NARROWBAND, WIDEBAND_STEREO, TINY)) {
            val bytes = decode(file)
            for (keep in 0..bytes.size step 19) {
                val cut = bytes.copyOf(keep)
                for (tolerant in listOf(false, true)) {
                    expectOnlyOwnFailures("cut to $keep") { AudioKodec.decode(cut, DecodeOptions(tolerant = tolerant)) }
                }
            }
            for (at in bytes.indices step 7) {
                for (mask in listOf(1, 0x10, 0xFF)) {
                    val mutated = fixCrc(bytes.copyOf().also { it[at] = (it[at].toInt() xor mask).toByte() })
                    expectOnlyOwnFailures("byte $at ^ $mask") { AudioKodec.decode(mutated) }
                }
            }
        }
    }

    private class Shape(val frames: Int, val channels: Int, val rate: Int)

    private fun decode(text: String): ByteArray = Base64.decodeOrNull(text)!!

    /** The smallest fixture, for the shared hostile-input sweep. */
    internal fun hostileFixture(): ByteArray = decode(TINY)

    /** [bytes] with every Ogg page's checksum made right again, so that damage reaches the decoder. */
    private fun fixCrc(bytes: ByteArray): ByteArray {
        var at = 0
        while (at + 27 <= bytes.size && bytes[at] == 'O'.code.toByte() && bytes[at + 1] == 'g'.code.toByte()) {
            val segments = bytes[at + 26].toInt() and 0xFF
            if (at + 27 + segments > bytes.size) break
            var size = 27 + segments
            for (s in 0 until segments) size += bytes[at + 27 + s].toInt() and 0xFF
            if (at + size > bytes.size) break
            for (i in 22 until 26) bytes[at + i] = 0
            var crc = 0
            for (i in at until at + size) {
                crc = crc xor ((bytes[i].toInt() and 0xFF) shl 24)
                repeat(8) { crc = if (crc and Int.MIN_VALUE != 0) (crc shl 1) xor 0x04C11DB7 else crc shl 1 }
            }
            for (i in 0 until 4) bytes[at + 22 + i] = (crc ushr (8 * i)).toByte()
            at += size
        }
        return bytes
    }

    private inline fun expectOnlyOwnFailures(what: String, block: () -> Unit) {
        try {
            block()
        } catch (_: AudioKodecException) {
            // Every failure has to be one of the library's own.
        } catch (e: Throwable) {
            throw AssertionError("$what threw ${e::class.simpleName}: ${e.message}", e)
        }
    }

