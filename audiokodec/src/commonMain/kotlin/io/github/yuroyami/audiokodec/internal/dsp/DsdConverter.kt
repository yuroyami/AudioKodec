package io.github.yuroyami.audiokodec.internal.dsp

/**
 * Converts DSD, a one-bit signal at a rate fs of 2.8224 MHz or a multiple of
 * it, into PCM at fs/32: 88.2 kHz from DSD64, 176.4 kHz from DSD128.
 *
 * The conversion is a choice of filter rather than a single correct answer,
 * so the design is stated here in full. Each bit counts as +1 or -1, and
 * three decimating lowpass stages follow, each a Kaiser-windowed sinc of odd
 * length with unit gain at zero frequency:
 *
 * - stage 1, at fs to fs/8: 79 taps, applied ten bytes of bits at a time
 *   through tables of each byte's contribution;
 * - stage 2, at fs/8 to fs/16: 27 taps;
 * - stage 3, at fs/16 to fs/32: 67 taps.
 *
 * Together they pass 0 to fs/128, 22.05 kHz from DSD64, within 2e-5 dB.
 * Every stage attenuates by at least 119 dB whatever would fold into the
 * output band 0 to fs/64 when it decimates, and stage 3 attenuates
 * everything from fs/64, the output's Nyquist frequency, upwards, so nothing
 * aliases. Between fs/128 and fs/64 the response falls away: that band holds
 * the noise a DSD modulator pushes out of the audio band.
 *
 * The filters are linear phase and the cascade is centred, so output sample
 * k is the signal at bit 32k with no delay; outside the stream the signal is
 * taken as zero. A sample depends on the 671 bits either side of its own,
 * so any range of output samples can be computed on its own, and a seek is
 * exact.
 *
 * The taps are generated by design-dsd-filters.py, which checks the
 * figures above.
 */
internal class DsdConverter {
    private var y1 = DoubleArray(0)
    private var y2 = DoubleArray(0)

    /**
     * Writes output samples [first] to [first] + [count] - 1 of one channel
     * into [out], from [outAt] in steps of [step].
     *
     * [window] holds the channel's bytes, most significant bit first in
     * time, from byte [windowStart]; it must cover [bytesNeeded] wherever
     * the stream has bytes. The stream has [totalBits] bits; bytes and bits
     * past them, and before the start, count as zero.
     */
    fun convert(window: ByteArray, windowStart: Long, totalBits: Long, first: Long, count: Int, out: FloatArray, outAt: Int, step: Int) {
        val totalBytes = (totalBits + 7) / 8
        val lastBits = (totalBits - (totalBytes - 1) * 8).toInt()
        val jLo = 4 * first - 2 * HALF3 - HALF2
        val n1 = 4 * (count - 1) + 4 * HALF3 + 2 * HALF2 + 1
        if (y1.size < n1) y1 = DoubleArray(n1)
        for (n in 0 until n1) {
            val j = jLo + n
            var sum = 0.0
            for (q in 0 until STAGE1_BYTES) {
                val b = j - 5 + q
                if (b < 0 || b >= totalBytes) continue
                val byte = window[(b - windowStart).toInt()].toInt() and 0xFF
                sum += if (b == totalBytes - 1 && lastBits < 8) partial(q, byte, lastBits) else tables[q][byte]
            }
            y1[n] = sum
        }
        val mLo = 2 * first - HALF3
        val n2 = 2 * (count - 1) + 2 * HALF3 + 1
        if (y2.size < n2) y2 = DoubleArray(n2)
        for (n in 0 until n2) {
            // y1 index 2m + i - jLo, for m = mLo + n.
            val base = (2 * (mLo + n) - HALF2 - jLo).toInt()
            var sum = 0.0
            for (i in 0 until STAGE2.size) sum += STAGE2[i] * y1[base + i]
            y2[n] = sum
        }
        var o = outAt
        for (k in 0 until count) {
            val base = 2 * k
            var sum = 0.0
            for (i in 0 until STAGE3.size) sum += STAGE3[i] * y2[base + i]
            out[o] = sum.toFloat()
            o += step
        }
    }

    /** A byte's contribution when only its first [bits] bits belong to the stream. */
    private fun partial(q: Int, byte: Int, bits: Int): Double {
        var sum = 0.0
        for (t in 0 until bits) {
            val s = 8 * q - 40 + t
            if (s < -HALF1) continue
            sum += if ((byte shr (7 - t)) and 1 == 1) STAGE1[s + HALF1] else -STAGE1[s + HALF1]
        }
        return sum
    }

